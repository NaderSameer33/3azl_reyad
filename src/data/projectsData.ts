/* ─── 3. Helper Query Functions ─────────────────────────────────────────── */

export function getAllProjects(): Project[] {
  return PROJECTS_DATABASE;
}

export function getProjectBySlug(slug: string): Project | undefined {
  return PROJECTS_DATABASE.find((p) => p.slug === slug);
}

export function getProjectsByCategory(categoryId: ProjectCategoryId): Project[] {
  return PROJECTS_DATABASE.filter((p) => p.category.id === categoryId);
}

export function getRelatedProjects(currentSlug: string, categoryId: ProjectCategoryId, limit = 3): Project[] {
  const sameCategory = PROJECTS_DATABASE.filter(
    (p) => p.slug !== currentSlug && p.category.id === categoryId
  );

  if (sameCategory.length >= limit) {
    return sameCategory.slice(0, limit);
  }

  const others = PROJECTS_DATABASE.filter(
    (p) => p.slug !== currentSlug && p.category.id !== categoryId
  );

  return [...sameCategory, ...others].slice(0, limit);
}

export function getAllCategories(): ProjectCategory[] {
  return PROJECT_CATEGORIES;
}

export function getAllProjectDistricts(): string[] {
  const districts = PROJECTS_DATABASE.map((p) => p.district);
  return Array.from(new Set(districts));
}
