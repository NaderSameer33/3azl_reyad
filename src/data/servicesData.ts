/* ─── Query Helper Functions ─────────────────────────────────────────────── */

export function getAllServiceCategories(): ServiceCategory[] {
  return servicesData;
}

export function getServiceCategoryBySlug(
  slug: string
): ServiceCategory | undefined {
  return servicesData.find((s) => s.slug === slug);
}

export function getAllCategoryArticles() {
  return servicesData.flatMap((cat) =>
    cat.articles.map((art) => ({
      ...art,
      categorySlug: cat.slug,
      categoryName: cat.name,
    }))
  );
}

export function getArticleBySlug(categorySlug: string, articleSlug: string) {
  const category = getServiceCategoryBySlug(categorySlug);
  if (!category) return undefined;
  const article = category.articles.find((a) => a.slug === articleSlug);
  if (!article) return undefined;
  return { article, category };
}

export function getProjectBySlug(categorySlug: string, projectSlug: string) {
  const category = getServiceCategoryBySlug(categorySlug);
  if (!category) return undefined;
  const project = category.projects.find((p) => p.slug === projectSlug);
  if (!project) return undefined;
  return { project, category };
}
